"""Bucket-scoped credentials owned by the disposable Longhorn backup store.

Only an account identifier enters mc arguments. Secret keys are generated by
mc, captured privately, and passed to clients through a mode-0600 env file.
A durable intent with an absent, randomly chosen identifier closes the gap
between server creation and receipt persistence; recovery verifies the exact
name, description, parent and explicit policy before revoking that identifier.
"""
import hashlib
import json
import os
import re
import secrets


def documents(raw):
    """mc --json emits a stream of possibly indented JSON documents."""
    result = []
    decoder = json.JSONDecoder()
    remainder = raw.strip()
    while remainder:
        value, end = decoder.raw_decode(remainder)
        if not isinstance(value, dict):
            raise ValueError('account response is not a JSON object')
        result.append(value)
        remainder = remainder[end:].lstrip()
    return result


def bucket_policy(bucket):
    if not re.fullmatch(r'longhorn-backup-[a-f0-9]{16}', bucket):
        raise ValueError('account policy requires the exact owned backup bucket')
    arn = 'arn:aws:s3:::' + bucket
    return {'Version': '2012-10-17', 'Statement': [
        {'Effect': 'Allow', 'Action': ['s3:GetBucketLocation', 's3:ListBucket', 's3:ListBucketMultipartUploads'],
         'Resource': [arn]},
        {'Effect': 'Allow', 'Action': ['s3:GetObject', 's3:PutObject', 's3:DeleteObject',
                                     's3:AbortMultipartUpload', 's3:ListMultipartUploadParts'],
         'Resource': [arn + '/*']}]}


def normalized_policy(value):
    """Ignore ordering and singleton-array encoding, never additional grants."""
    if isinstance(value, str):
        value = json.loads(value)
    if (not isinstance(value, dict) or set(value) != {'Version', 'Statement'} or
            value['Version'] != '2012-10-17' or not isinstance(value['Statement'], list)):
        raise ValueError('account policy structure differs')
    result = []
    for statement in value['Statement']:
        if (not isinstance(statement, dict) or set(statement) - {'Effect', 'Action', 'Resource', 'Sid'} or
                statement.get('Sid') or statement.get('Effect') != 'Allow'):
            raise ValueError('account policy statement differs')
        fields = []
        for key in ('Action', 'Resource'):
            items = statement.get(key)
            if isinstance(items, str):
                items = [items]
            if not isinstance(items, list) or not items or not all(isinstance(item, str) for item in items):
                raise ValueError('account policy field differs')
            fields.append(tuple(sorted(items)))
        result.append(tuple(fields))
    return sorted(result)


def native_refusal(result, codes, *, operation=None, target=None):
    if result.returncode == 0:
        return False
    try:
        values = documents(result.stdout)
    except (TypeError, ValueError):
        return False
    if len(values) != 1 or values[0].get('status') != 'error':
        return False
    error = values[0].get('error')
    if not isinstance(error, dict) or not isinstance(error.get('cause'), dict):
        return False
    cause = error['cause']; native = cause.get('error')
    if not isinstance(native, dict):
        return False
    if isinstance(native.get('Code'), str):
        return native['Code'] in codes
    # Pinned mc getObjectStat converts HEAD errors to client error types.
    # Bind the exact serialized type, message, operation and owned target;
    # a permission-like string or an empty cause alone proves nothing.
    if (not isinstance(target, str) or not target.startswith('lh/') or
            error.get('type') != 'fatal'):
        return False
    if operation == 'cat' and 'AccessDenied' in codes:
        path = 'https://127.0.0.1:9000/' + target[3:]
        return (error.get('message') == 'Unable to read from `' + target + '`.' and
                native == {'Path': path} and
                cause.get('message') == 'Insufficient permissions to access this path `' + path + '`')
    if operation == 'stat' and 'NoSuchKey' in codes:
        return (error.get('message') == 'Unable to stat `' + target + '`.' and
                native == {} and cause.get('message') == 'Object does not exist')
    return False


def failure_stage(raw):
    """Only fixed mc message literals may enter a shared traceback."""
    stages = {'unable to read the policy document': 'policy-read',
              'unable to parse the policy document': 'policy-parse',
              'Unable to add service account.': 'create-request',
              'Unable to initialize admin connection.': 'admin-client'}
    try:
        values = documents(raw)
        if len(values) == 1 and isinstance(values[0].get('error'), dict):
            return stages.get(values[0]['error'].get('message'), 'unclassified')
    except (TypeError, ValueError):
        pass
    return 'unclassified'


class Accounts:
    def __init__(self, lab, store):
        self.lab, self.store = lab, store
        self.record = store.directory / 'accounts.json'

    def context(self):
        row = self.store.receipt()
        container = self.store.inspect(row)
        if not container or not container.get('State', {}).get('Running'):
            raise ValueError('account fixture requires its running backup store')
        return row, container

    def read(self):
        if self.record.is_symlink():
            raise ValueError('account journal is a symlink')
        info = self.record.stat()
        if info.st_uid != os.getuid() or info.st_mode & 0o077:
            raise ValueError('account journal is not private')
        row = json.loads(self.record.read_text()); store, container = self.context()
        if (row['run_id'] != store['run_id'] or row['cluster_uid'] != store['cluster_uid'] or
                row['container_id'] != container['Id'] or row['bucket'] != store['bucket'] or
                normalized_policy(row['policy']) != normalized_policy(bucket_policy(store['bucket']))):
            raise ValueError('account fixture identity or bucket policy changed')
        for key, account in row['accounts'].items():
            if (not re.fullmatch(r'lh[a-f0-9]{18}', key) or account['name'] != key or
                    account['description'] != 'kubeauto-longhorn:' + row['run_id'] + ':' + key or
                    account['phase'] not in ('intent', 'ready', 'revoked')):
                raise ValueError('account intent identity differs')
        return row

    def initialize(self):
        if self.record.exists() or self.record.is_symlink():
            raise ValueError('previous account fixture needs recovery')
        row, container = self.context()
        root_env = self.store.directory / 'server.env'
        if root_env.is_symlink() or root_env.stat().st_mode & 0o077:
            raise ValueError('backup root environment is not private')
        values = dict(line.split('=', 1) for line in root_env.read_text().splitlines())
        self.lab.write_private(self.record, {'run_id': row['run_id'], 'cluster_uid': row['cluster_uid'],
            'container_id': container['Id'], 'bucket': row['bucket'], 'parent': values['MINIO_ROOT_USER'],
            'policy': bucket_policy(row['bucket']), 'accounts': {}})

    def command(self, *arguments, account=None, allow_revoked=False, stdin=None, check=True):
        _, container = self.context()
        environment = self.store.directory / 'mc.env'
        if account:
            row = self.read()
            permitted = ('ready', 'revoked') if allow_revoked else ('ready',)
            if (account not in row['accounts'] or row['accounts'][account]['phase'] not in permitted or
                    not row['accounts'][account].get('secret')):
                raise ValueError('account is not a ready owned client')
            material = row['accounts'][account]['secret']
            if not isinstance(material, str) or not re.fullmatch(r'[A-Za-z0-9+/=]{8,128}', material):
                raise ValueError('account secret is outside the generated credential alphabet')
            environment = self.store.directory / (account + '.env')
            if environment.exists() or environment.is_symlink():
                raise ValueError('previous account environment needs recovery')
            # MC_HOST_ is a raw credential grammar, not URL userinfo:
            # parseEnvURLStr captures the key before URL parsing/decoding.
            text = ('MC_CONFIG_DIR=/tmp/longhorn-mc\nMC_HOST_lh=https://' + account + ':' +
                    material + '@127.0.0.1:9000\n')
            with os.fdopen(os.open(environment, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'w') as stream:
                stream.write(text)
                environment_identity = os.fstat(stream.fileno())
        try:
            # Pinned pipe uses the local flag for progress suppression, even
            # when the global --json already controls its final JSON message.
            if arguments and arguments[0] == 'pipe':
                arguments = ('pipe', '--json', *arguments[1:])
            # Suppress raw mc errors too: they may contain identity or signed URLs.
            result = self.lab.execute(['docker', 'exec', *(['-i'] if stdin is not None else []),
                                       '--env-file', str(environment), container['Id'],
                                       'mc', '--json', *arguments], stdin=stdin, check=False, timeout=120)
            if check and result.returncode:
                self.fail(result, failure_stage(result.stdout))
            return result
        finally:
            if account:
                info = environment.lstat()
                if (environment.is_symlink() or
                        (info.st_dev, info.st_ino) != (environment_identity.st_dev, environment_identity.st_ino)):
                    raise ValueError('account environment identity changed')
                environment.unlink()

    def fail(self, result, stage):
        # Preserve native output outside disposable store data, including
        # unexpected successful output. Never include its contents in errors.
        diagnostic = self.lab.DIRECTORY / ('longhorn-account-failure-' + secrets.token_hex(12) + '.json')
        self.lab.write_private(diagnostic, {'rc': result.returncode, 'stdout': result.stdout,
                                            'stderr': result.stderr})
        raise ValueError('private account command failed rc=' + str(result.returncode) +
                         ' stage=' + stage + ' evidence=' + str(diagnostic)) from None

    def json_response(self, result):
        try:
            return documents(result.stdout)
        except (TypeError, ValueError):
            self.fail(result, 'response-json')

    def require_refusal(self, result, codes, stage, *, operation=None, target=None):
        if not native_refusal(result, codes, operation=operation, target=target):
            self.fail(result, stage)

    def listing(self):
        # svcacc-only suppresses the parent record for an empty account set.
        # Default listType=all retains that authenticated identity even when
        # both arrays are empty; only svcaccs grants ownership below.
        response = self.command('admin', 'accesskey', 'list', '--self', 'lh/')
        rows = self.json_response(response)
        if len(rows) != 1 or rows[0].get('status') != 'success' or rows[0].get('user') != self.read()['parent']:
            raise ValueError('account listing parent or status differs')
        accounts = rows[0].get('svcaccs') or []
        if not isinstance(accounts, list) or any(not isinstance(item, dict) or not item.get('accessKey') for item in accounts):
            raise ValueError('account listing structure differs')
        identifiers = [item['accessKey'] for item in accounts]
        if len(set(identifiers)) != len(identifiers):
            raise ValueError('account listing repeats an identifier')
        return set(identifiers)

    def verify(self, identifier):
        row = self.read(); account = row['accounts'][identifier]
        values = self.json_response(self.command('admin', 'accesskey', 'info', 'lh/', identifier))
        if len(values) != 1:
            raise ValueError('account info response count differs')
        value = values[0]
        if (value.get('status') != 'success' or value.get('accessKey') != identifier or
                value.get('parentUser') != row['parent'] or value.get('name') != account['name'] or
                value.get('description') != account['description'] or value.get('impliedPolicy', False) is not False or
                value.get('accountStatus') != 'on' or
                normalized_policy(value.get('policy')) != normalized_policy(row['policy'])):
            raise ValueError('account identity or explicit policy differs')

    def create(self):
        row = self.read()
        # NewServiceAccount uses CreateNewCredentialsWithMetadata (max 20),
        # unlike the minimum-only validation used by other credential paths.
        identifier = 'lh' + secrets.token_hex(9)
        if identifier in self.listing():
            raise ValueError('account creation identifier already exists')
        row['accounts'][identifier] = {'name': identifier,
            'description': 'kubeauto-longhorn:' + row['run_id'] + ':' + identifier, 'phase': 'intent'}
        self.lab.write_private(self.record, row)
        # The pinned mc reads --policy with os.ReadFile; pass the policy
        # directly through docker exec stdin without a temporary container file.
        response = self.command('admin', 'accesskey', 'create', '--access-key', identifier,
                                '--name', identifier, '--description', row['accounts'][identifier]['description'],
                                '--policy', '/dev/stdin', '--expiry-duration', '24h', 'lh/',
                                stdin=json.dumps(row['policy']))
        values = self.json_response(response)
        if (len(values) != 1 or values[0].get('status') != 'success' or
                values[0].get('accessKey') != identifier or
                not isinstance(values[0].get('secretKey'), str) or
                not re.fullmatch(r'[A-Za-z0-9+/=]{8,128}', values[0]['secretKey'])):
            raise ValueError('account creation response differs')
        row['accounts'][identifier].update(secret=values[0]['secretKey'], phase='ready')
        self.lab.write_private(self.record, row)
        self.verify(identifier)
        return identifier

    def revoke(self, identifier):
        row = self.read()
        if identifier not in row['accounts']:
            raise ValueError('account revocation has no durable intent')
        if identifier in self.listing():
            if row['accounts'][identifier]['phase'] == 'revoked':
                raise ValueError('a revoked account identifier was recreated')
            self.verify(identifier)
            values = self.json_response(self.command('admin', 'accesskey', 'remove', 'lh/', identifier))
            if len(values) != 1 or values[0].get('status') != 'success' or values[0].get('accessKey') != identifier:
                raise ValueError('account revocation response differs')
        if identifier in self.listing():
            raise ValueError('revoked account remains in native listing')
        row['accounts'][identifier]['phase'] = 'revoked'
        self.lab.write_private(self.record, row)

    def cleanup(self):
        credentials = self.lab.DIRECTORY / 'longhorn-recurring-credentials.json'
        if credentials.exists() or credentials.is_symlink():
            raise ValueError('recurring credential references must recover before account revocation')
        if not self.record.exists() and not self.record.is_symlink():
            return
        row = self.read()
        for identifier in row['accounts']:
            environment = self.store.directory / (identifier + '.env')
            if environment.is_symlink():
                raise ValueError('account environment is a symlink')
            self.revoke(identifier)
            if environment.exists():
                environment.unlink()
        self.record.unlink()
        print('LONGHORN_BACKUP_ACCOUNTS_CLEAN_PASS', flush=True)

    def qualify(self):
        """Prove two restricted identities, native denial and old-key revocation."""
        row = self.read(); baseline = self.listing()
        def buckets(account=None):
            values = self.json_response(self.command('ls', 'lh/', account=account))
            names = []
            for value in values:
                name = value.get('key', '')
                if (value.get('status') != 'success' or value.get('type') != 'folder' or
                        not re.fullmatch(r'[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]/', name)):
                    raise ValueError('bucket listing structure differs')
                names.append(name[:-1])
            if len(names) != len(set(names)):
                raise ValueError('bucket listing repeats a bucket')
            return set(names)

        original_buckets = buckets()
        denied_bucket = row['bucket'] + '-denied'
        if row['bucket'] not in original_buckets or denied_bucket in original_buckets:
            raise ValueError('account canary bucket identity differs')
        # This store is an exclusive, ID-bound disposable container. On failure
        # its owner removes the container/data after revoking account intents.
        self.command('mb', 'lh/' + denied_bucket)
        denied_target = 'lh/' + denied_bucket + '/authorization-canary'
        denied_payload = 'Longhorn denied bucket control ' + row['run_id']
        self.command('pipe', denied_target, stdin=denied_payload)
        if self.command('cat', denied_target).stdout != denied_payload:
            raise ValueError('root denied-bucket control bytes differ')
        first, second = self.create(), self.create()
        target = 'lh/' + row['bucket'] + '/account-qualification'
        payload = 'Longhorn account qualification ' + row['run_id']
        for key in (first, second):
            values = self.json_response(self.command('pipe', target, account=key, stdin=payload))
            if len(values) != 1 or values[0].get('status') != 'success':
                raise ValueError('restricted account did not confirm object upload')
            if self.command('cat', target, account=key).stdout != payload:
                raise ValueError('restricted account object bytes differ')
            values = self.json_response(self.command('ls', 'lh/' + row['bucket'] + '/', account=key))
            if not any(value.get('status') == 'success' and value.get('type') == 'file' and
                       value.get('key') == 'account-qualification' for value in values):
                raise ValueError('restricted account object is missing from listing')
            # Pinned MinIO filters ListBuckets by ListBucket/GetBucketLocation.
            # Lack of ListAllMyBuckets does not imply an AccessDenied response.
            if buckets(key) != {row['bucket']}:
                raise ValueError('restricted bucket listing escaped its explicit policy')
            for arguments in (('cat', denied_target), ('admin', 'user', 'list', 'lh/')):
                self.command(*arguments)  # Same operation is allowed for the root control.
                refusal = self.command(*arguments, account=key, check=False)
                operation = 's3-read' if arguments[0] == 'cat' else 'admin-list'
                self.require_refusal(refusal, {'AccessDenied'}, 'native authorization refusal (' + operation + ')',
                                     operation=arguments[0], target=arguments[1])
                if self.command('cat', target, account=key).stdout != payload:
                    raise ValueError('legal object access failed after authorization refusal')
            self.command('rm', target, account=key)
            self.require_refusal(self.command('stat', target, account=key, check=False), {'NoSuchKey'},
                                 'restricted object deletion was not observed', operation='stat', target=target)
        self.command('pipe', target, account=second, stdin=payload)
        self.revoke(first)
        refusal = self.command('cat', target, account=first, allow_revoked=True, check=False)
        self.require_refusal(refusal, {'InvalidAccessKeyId'}, 'native credential refusal')
        if self.command('cat', target, account=second).stdout != payload:
            raise ValueError('replacement credential did not preserve confirmed object access')
        self.command('rm', target, account=second)
        missing = self.command('stat', target, account=second, check=False)
        self.require_refusal(missing, {'NoSuchKey'}, 'restricted object deletion was not observed',
                             operation='stat', target=target)
        self.revoke(second)
        if self.listing() != baseline:
            raise ValueError('account qualification changed the original account set')
        if self.command('cat', denied_target).stdout != denied_payload:
            raise ValueError('denied-bucket bytes changed during authorization checks')
        self.command('rm', denied_target)
        self.command('rb', 'lh/' + denied_bucket)
        if buckets() != original_buckets:
            raise ValueError('account qualification changed the original bucket set')
        print('LONGHORN_BACKUP_ACCOUNTS_QUALIFIED accounts=2 policy=bucket-only '
              'authorization_refusals=4 revoked_key_refusals=1 sha256=' +
              hashlib.sha256(payload.encode()).hexdigest(), flush=True)
